import { describe, it, expect, beforeEach } from 'vitest';
import {
  createPendingBooking,
  getBookingByIdOrReference,
  listAllBookings,
  listAllSupportRequests,
  updateSupportRequestStatus,
  listCatalog,
  upsertCatalogRecord,
} from '@/lib/booking/store';
import { calculateCompleteFare } from '@/lib/pricing/engine';
import { getDeterministicFlightOffers } from '@/lib/flights/dataset';

import { generateItineraryPdfBytes } from '@/lib/pdf/generator';

describe('DummyTickets Complete Platform Transformation Tests', () => {
  it('allows complete guest booking creation without user authentication', async () => {
    const offer = getDeterministicFlightOffers({
      from: 'DEL',
      to: 'LHR',
      departDate: '2026-12-15',
    })[0];

    const fareSnapshot = calculateCompleteFare({
      offer,
      adults: 1,
      cabin: 'economy',
    });

    const idempotencyKey = `test-guest-idem-${Date.now()}`;
    const { booking, deduplicated } = await createPendingBooking({
      flightOfferId: offer.id,
      fareSnapshot,
      departDate: '2026-12-15',
      contactEmail: 'traveler.guest@example.com',
      contactPhone: '+91 9848011223',
      passengers: [
        {
          passengerType: 'adult',
          firstName: 'Siddharth',
          lastName: 'Sharma',
          gender: 'male',
          nationality: 'IN',
          passportNumber: 'Z8765432',
        },
      ],
      idempotencyKey,
      userId: undefined, // Guest customer — NO account required
    });

    expect(booking).toBeDefined();
    expect(booking.userId).toBeNull();
    expect(booking.contactEmail).toBe('traveler.guest@example.com');
    expect(booking.bookingReference).toMatch(/^DT-[A-Z0-9]+$/);
    expect(deduplicated).toBe(false);

    // Verify lookup by booking reference without login
    const lookedUp = await getBookingByIdOrReference(booking.bookingReference);
    expect(lookedUp).toBeDefined();
    expect(lookedUp?.id).toBe(booking.id);
  });

  it('strictly separates Internal Booking Reference from Airline PNR', async () => {
    const offer = getDeterministicFlightOffers({
      from: 'BOM',
      to: 'DXB',
      departDate: '2026-12-20',
    })[0];

    const fareSnapshot = calculateCompleteFare({
      offer,
      adults: 1,
    });

    const { booking } = await createPendingBooking({
      flightOfferId: offer.id,
      fareSnapshot,
      departDate: '2026-12-20',
      contactEmail: 'pnr.test@example.com',
      contactPhone: '+91 9811234567',
      passengers: [
        {
          passengerType: 'adult',
          firstName: 'Ananya',
          lastName: 'Verma',
        },
      ],
      idempotencyKey: `idem-pnr-test-${Date.now()}`,
    });

    // Fresh booking has internal reference generated by DummyTickets, but NO airline PNR
    expect(booking.bookingReference).toBeTruthy();
    expect(booking.airlinePnr).toBeUndefined();
  });

  it('manages support requests and updates inquiry status', async () => {
    const requests = await listAllSupportRequests();
    expect(requests.length).toBeGreaterThan(0);

    const first = requests[0];
    const updated = await updateSupportRequestStatus(first.id, 'resolved', 'Itinerary reissued successfully.');
    expect(updated?.status).toBe('resolved');
    expect(updated?.adminReply).toContain('Itinerary reissued successfully.');
  });

  it('persists route network additions through catalog', async () => {
    const newRoute = {
      id: 'route-hyd-dxb-test',
      slug: 'hyd-to-dxb-flights',
      origin_city: 'Hyderabad',
      origin_iata: 'HYD',
      destination_city: 'Dubai',
      destination_iata: 'DXB',
      starting_fare_inr: 499,
      daily_flights_count: 3,
      is_active: true,
    };

    const routeId = await upsertCatalogRecord('route_page', newRoute);
    expect(routeId).toBe('route-hyd-dxb-test');

    const allRoutes = await listCatalog('route_page');
    expect(allRoutes.some((r) => r.id === 'route-hyd-dxb-test')).toBe(true);
  });

  it('generates authentic GDS e-ticket PDF without printing company name', async () => {
    const offer = getDeterministicFlightOffers({
      from: 'DEL',
      to: 'LHR',
      departDate: '2026-12-15',
    })[0];
    const fareSnapshot = calculateCompleteFare({
      offer,
      adults: 1,
      cabin: 'economy',
    });
    const { booking } = await createPendingBooking({
      flightOfferId: offer.id,
      fareSnapshot,
      departDate: '2026-12-15',
      contactEmail: 'pax@example.com',
      contactPhone: '+91 9999999999',
      passengers: [{ passengerType: 'adult', firstName: 'Aarav', lastName: 'Kapoor' }],
      idempotencyKey: `pdf-test-${Date.now()}`,
    });

    const pdfBytes = await generateItineraryPdfBytes(booking);
    expect(pdfBytes).toBeInstanceOf(Uint8Array);
    expect(pdfBytes.length).toBeGreaterThan(1000);

    const pdfString = Buffer.from(pdfBytes).toString('utf-8');
    // Ensure strict compliance: NO company names on the ticket
    expect(pdfString).not.toMatch(/DummyTicket/i);
    expect(pdfString).not.toMatch(/MyJet24/i);
  });
});
